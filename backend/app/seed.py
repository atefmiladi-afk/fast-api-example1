def seed_if_empty(db: Session) -> None:
    for cat in CATEGORIES:
        category = db.query(Category).filter(Category.slug == cat["slug"]).first()
        if not category:
            category = Category(
                slug=cat["slug"],
                name_de=cat["name_de"],
                name_en=cat["name_en"],
                description=cat["description"],
                emoji=cat["emoji"],
                color=cat["color"],
                image_url=cat["image_url"],
            )
            db.add(category)
            db.flush()
        existing = {w.german for w in category.words}
        for german, article, english, example_de, example_en, image_url in cat["words"]:
            if german in existing:
                continue
            db.add(
                Word(
                    category_id=category.id,
                    german=german,
                    article=article,
                    english=english,
                    example_de=example_de,
                    example_en=example_en,
                    image_url=image_url,
                    audio_hint=german,
                )
            )
    db.commit()
